/* 并入主数据：先补学科标签，再追加新增机构 */
(function () {
  if (!window.DATA || !window.INTERN_MORE) return;
  var more = window.INTERN_MORE;
  var companies = (window.DATA.companies || []).concat(more.companies || []);
  var byName = {};
  companies.forEach(function (c) { byName[c.name] = c; });
  function union(a, b) {
    var out = (a || []).slice();
    (b || []).forEach(function (x) { if (out.indexOf(x) < 0) out.push(x); });
    return out;
  }
  var PATCH = more.patches || {};
  Object.keys(PATCH).forEach(function (name) {
    var c = byName[name];
    if (!c) return;
    var p = PATCH[name];
    if (p.tags) c.tags = union(c.tags, p.tags);
    if (p.disciplines) { c.disciplines = union(c.disciplines, p.disciplines); delete c.discInferred; }
    if (p.jobs && !c.jobs) c.jobs = p.jobs;
  });
  window.DATA.companies = companies;
  if (more.updatedAt) window.DATA.updatedAt = more.updatedAt;
})();
